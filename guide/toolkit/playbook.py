#!/usr/bin/env python3
# /// script
# requires-python = ">=3.11"
# dependencies = ["pyyaml"]
# ///
"""Antora playbooks that also work from a linked git worktree (FR-016a).

Antora cannot read `url: .` inside a linked worktree, where `.git` is a file. In that
case this script writes build/playbook.yml (or build/playbook-internal.yml): every
`url: .` content source points at the main repository with `branches: <worktree
branch>` and `worktrees: <worktree name>`, and relative paths (output.dir, a local UI
bundle, local extensions) become absolute. In a main checkout the committed
site.yml / site-internal.yml is used as is.

Usage: uv run tools/guide/playbook.py path [--internal] [--root DIR]   (prints the path)
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

import yaml

import guidecfg

URL_RE = guidecfg.URL_RE


def is_linked_worktree(root: Path) -> bool:
    return (Path(root) / ".git").is_file()


def _git(root: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(root), *args], check=True, capture_output=True,
                          text=True).stdout.strip()


def _absolute(value: str, base: Path) -> str:
    if URL_RE.match(value) or value.startswith("@") or Path(value).is_absolute():
        return value
    if value.startswith((".", "/")) or "/" in value:
        return str((base / value).resolve())
    return value


def path(root: Path, internal: bool = False) -> Path:
    """The playbook to build from; generated when root is a linked worktree."""
    root = Path(root).resolve()
    name = "site-internal.yml" if internal else "site.yml"
    source = root / name
    if not is_linked_worktree(root):
        return source

    git_dir = Path(_git(root, "rev-parse", "--absolute-git-dir"))
    common = Path(_git(root, "rev-parse", "--path-format=absolute", "--git-common-dir"))
    main_repo = common.parent
    worktree_name = git_dir.name
    branch = _git(root, "rev-parse", "--abbrev-ref", "HEAD")
    if branch == "HEAD":
        raise SystemExit(f"{root} is a linked worktree in detached HEAD state; check out a branch first")

    data = yaml.safe_load(source.read_text()) or {}
    for src in (data.get("content") or {}).get("sources") or []:
        if str(src.get("url", "")).rstrip("/") in (".", "./"):
            src["url"] = str(main_repo)
            src["branches"] = branch
            src["worktrees"] = worktree_name
    output = data.setdefault("output", {})
    output["dir"] = _absolute(output.get("dir") or ("./build/site-internal" if internal else "./build/site"), root)
    bundle = (data.get("ui") or {}).get("bundle")
    if isinstance(bundle, dict) and bundle.get("url"):
        bundle["url"] = _absolute(str(bundle["url"]), root)
    antora = data.get("antora") or {}
    if antora.get("extensions"):
        antora["extensions"] = [
            _absolute(e, root) if isinstance(e, str)
            else ({**e, "require": _absolute(e["require"], root)} if isinstance(e, dict) and "require" in e else e)
            for e in antora["extensions"]
        ]
    for key in ("supplemental_files",):
        ui = data.get("ui") or {}
        if isinstance(ui.get(key), str):
            ui[key] = _absolute(ui[key], root)

    out = root / "build" / ("playbook-internal.yml" if internal else "playbook.yml")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# Generated by tools/guide/playbook.py for a linked git worktree; do not edit.\n"
                   + yaml.safe_dump(data, sort_keys=False))
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Antora playbook path (linked-worktree aware)")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("path")
    p.add_argument("--internal", action="store_true")
    p.add_argument("--root", type=Path, default=Path("."))
    args = parser.parse_args(argv)
    print(path(args.root, args.internal))
    return 0


if __name__ == "__main__":
    sys.exit(main())
